#!/usr/bin/env python3
"""Mirror only source-identified, actual AMR/AGV manufacturer logo graphics.

Never reconstruct a trademark or substitute a random favicon/product photo.
Unavailable logos remain one plain text brand name in the browser.
"""
from __future__ import annotations
import base64
import concurrent.futures
import hashlib
import io
import json
import re
import urllib.request
from urllib.parse import urlparse
import xml.etree.ElementTree as ET
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "assets" / "amr-logos"
MAX_BYTES = 1_800_000
HEADERS = {
    "User-Agent": "Mozilla/5.0 (compatible; RoboQuoOriginalMakerLogos/1.0)",
    "Accept": "image/svg+xml,image/png,image/jpeg,image/webp,image/*;q=0.8",
}
BAD_TAGS = {"script", "foreignObject", "iframe", "object", "embed"}

def safe_svg(source: bytes) -> str:
    if re.search(rb"<svg(?:\\s|>)", source[:4096], re.I):
        root = ET.fromstring(source)
        if root.tag.rsplit("}", 1)[-1] != "svg":
            raise ValueError("SVG root mismatch")
        for elem in root.iter():
            if elem.tag.rsplit("}", 1)[-1] in BAD_TAGS:
                raise ValueError("forbidden SVG element")
            for key, val in elem.attrib.items():
                k = key.rsplit("}", 1)[-1].lower()
                if k.startswith("on") or (k in ("href", "src") and re.match(r"(?i)(?:https?:|javascript:)", val)):
                    raise ValueError("unsafe SVG attribute")
        text = source.decode("utf-8-sig")
        if len(text) < 150:
            raise ValueError("SVG too short")
        return text
    with Image.open(io.BytesIO(source)) as img:
        img.verify()
    with Image.open(io.BytesIO(source)) as img:
        img.load()
        w, h = img.size
        if w < 40 or h < 20 or w > 12000 or h > 12000:
            raise ValueError("unexpected logo dimensions")
        if img.format not in ("PNG", "JPEG", "WEBP"):
            buf = io.BytesIO()
            img.convert("RGBA").save(buf, "PNG")
            source = buf.getvalue()
            mime = "image/png"
        else:
            mime = {"PNG":"image/png","JPEG":"image/jpeg","WEBP":"image/webp"}[img.format]
    data = base64.b64encode(source).decode("ascii")
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" '
            f'viewBox="0 0 {w} {h}"><image width="{w}" height="{h}" '
            f'href="data:{mime};base64,{data}"/></svg>')

def fetch_one(row: dict) -> dict:
    brand, slug = row["name"], row["slug"]
    dest = OUT / (slug + ".svg")
    errors = []
    for url in row.get("logoSources", []):
        if not url.startswith("https://"):
            errors.append("Not HTTPS")
            continue
        try:
            req = urllib.request.Request(url, headers=HEADERS)
            with urllib.request.urlopen(req, timeout=22) as resp:
                raw = resp.read(MAX_BYTES + 1)
                if len(raw) > MAX_BYTES or resp.status != 200:
                    raise ValueError("Invalid image response")
            image = safe_svg(raw)
            dest.write_text(image, encoding="utf-8")
            sha = hashlib.sha256(image.encode()).hexdigest()
            return {"name":brand,"status":"downloaded","host":urlparse(url).hostname,
                    "sha256":sha,"bytes":len(image.encode())}
        except Exception as exc:
            errors.append(type(exc).__name__+": "+str(exc)[:140])
    if dest.exists() and dest.stat().st_size > 150:
        raw = dest.read_bytes()
        return {"name":brand,"status":"kept-existing",
                "sha256":hashlib.sha256(raw).hexdigest(),"bytes":len(raw)}
    return {"name":brand,"status":"unverified","errors":errors[:3]}

def main() -> None:
    data = json.loads((ROOT/"amr-maker-sources.json").read_text("utf-8"))
    makers = data["makers"]
    assert len(makers) == 19 and len({row["name"] for row in makers}) == 19
    OUT.mkdir(parents=True, exist_ok=True)
    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
        results = list(pool.map(fetch_one, makers))
    local = {}
    for row, r in zip(makers, results):
        if r["status"] in ("downloaded", "kept-existing"):
            local[row["name"]] = "./assets/amr-logos/"+row["slug"]+".svg?v="+r["sha256"][:10]
    report = {"total":len(makers),"mirrored":len(local),
              "unverified":[r["name"] for r in results if r["status"] == "unverified"],"details":results}
    (OUT/"SOURCE_REPORT.json").write_text(json.dumps(report,ensure_ascii=False,indent=2)+"\\n","utf-8")
    (ROOT/"amr-maker-local-map.js").write_text(
        "/* Only downloaded original company logos; generated by tools/sync-amr-logos.py. */\\n"+
        "window.RQ_AMR_MAKER_LOCAL = "+json.dumps(local,ensure_ascii=False,sort_keys=True)+";\\n","utf-8")
    print("Verified original AMR maker logo mirrors",len(local),"/",len(makers))
    print("Unverified",report["unverified"])

if __name__ == "__main__":
    main()
